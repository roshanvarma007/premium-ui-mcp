// Derived, platform-neutral values shared by every adapter. Keeping this logic in
// one place guarantees that web and Android outputs agree with each other.
import { contrastHex } from '../a11y/contrast.js';
import {
  type Direction,
  type FontFamily,
  type Palette,
  TYPE_ROLES,
  type TypeRole,
  type TypeStyle,
} from '../schema/direction.schema.js';

export const PALETTE_KEYS = [
  'bg',
  'surface',
  'surface_alt',
  'text',
  'text_muted',
  'border',
  'border_strong',
  'accent',
  'on_accent',
  'link',
  'success',
  'warning',
  'error',
] as const;
export type PaletteKey = (typeof PALETTE_KEYS)[number];

/** Palette with `link` resolved (falls back to accent) and on-colors for semantic fills. */
export interface ResolvedPalette extends Required<Palette> {
  on_error: string;
  on_success: string;
  on_warning: string;
}

/** Picks whichever of the two candidates contrasts more with `fill` (ties: first). */
function bestOn(fill: string, a: string, b: string): string {
  return contrastHex(a, fill) >= contrastHex(b, fill) ? a : b;
}

export function resolvePalette(p: Palette): ResolvedPalette {
  return {
    ...p,
    link: p.link ?? p.accent,
    on_error: bestOn(p.error, p.surface, p.text),
    on_success: bestOn(p.success, p.surface, p.text),
    on_warning: bestOn(p.warning, p.surface, p.text),
  };
}

export type FamilyKey = 'display' | 'body' | 'mono';

export function roleFamily(role: TypeRole, style: TypeStyle): FamilyKey {
  return style.family ?? (role === 'display' || role === 'headline' ? 'display' : 'body');
}

export function families(d: Direction): Array<{ key: FamilyKey; family: FontFamily }> {
  const out: Array<{ key: FamilyKey; family: FontFamily }> = [
    { key: 'display', family: d.typography.display_family },
    { key: 'body', family: d.typography.body_family },
  ];
  if (d.typography.mono_family) out.push({ key: 'mono', family: d.typography.mono_family });
  return out;
}

export function typeRoles(
  d: Direction,
): Array<{ role: TypeRole; style: TypeStyle; family: FamilyKey }> {
  return TYPE_ROLES.map((role) => {
    const style = d.typography.scale[role];
    return { role, style, family: roleFamily(role, style) };
  });
}

const WEIGHT_NAMES: Record<number, string> = {
  100: 'thin',
  200: 'extralight',
  300: 'light',
  400: 'regular',
  500: 'medium',
  600: 'semibold',
  700: 'bold',
  800: 'extrabold',
  900: 'black',
};

export function weightName(weight: number): string {
  return WEIGHT_NAMES[weight] ?? `w${weight}`;
}

/** "JetBrains Mono" -> "jetbrains_mono" (valid Android resource and file name). */
export function fontSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

/** Same name with dashes, for web file names: "jetbrains-mono". */
export function fontKebab(name: string): string {
  return fontSlug(name).replace(/_/g, '-');
}

/** Spacing tokens named by multiples of the base unit: 16px on a 4 grid -> "4". */
export function spacingTokens(d: Direction): Array<{ name: string; value: number }> {
  return d.spacing.scale.map((value) => ({
    name: String(value / d.spacing.base).replace('.', '_'),
    value,
  }));
}

export function easingPoints(d: Direction): [number, number, number, number] {
  const nums = d.motion.easing.match(/-?[\d.]+/g)!.map(Number);
  return [nums[0]!, nums[1]!, nums[2]!, nums[3]!];
}

/** Formats a number without trailing zeros: 0.020 -> "0.02", 16 -> "16". */
export function num(n: number): string {
  return String(Number(n.toFixed(4)));
}

/** snake_case -> camelCase */
export function camel(s: string): string {
  return s.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** snake_case -> kebab-case */
export function kebab(s: string): string {
  return s.replace(/_/g, '-');
}

export function generatedHeader(d: Direction, commentPrefix: string): string {
  return [
    `${commentPrefix} Generated by premium-ui-mcp from the "${d.id}" design direction (v${d.version}).`,
    `${commentPrefix} Use these tokens everywhere; do not hardcode colors, sizes, radii or fonts in screens.`,
  ].join('\n');
}
