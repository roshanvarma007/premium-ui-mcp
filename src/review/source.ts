// Source helpers: file classification, comment blanking (line numbers preserved), line math.

export type Lang = 'css' | 'html' | 'js' | 'kotlin' | 'xml' | 'other';

export function langOf(path: string): Lang {
  const p = path.toLowerCase();
  if (/\.(css|scss|sass|less|pcss)$/.test(p)) return 'css';
  if (/\.(html?|vue|svelte|astro)$/.test(p)) return 'html';
  if (/\.(m?[jt]sx?|cjs|cts|mts)$/.test(p)) return 'js';
  if (/\.(kt|kts)$/.test(p)) return 'kotlin';
  if (/\.xml$/.test(p)) return 'xml';
  return 'other';
}

/** Generated theme files define tokens; literal values are expected there. */
export function isTokenFile(path: string, content: string): boolean {
  if (content.includes('Generated by premium-ui-mcp')) return true;
  const p = path.replace(/\\/g, '/').toLowerCase();
  return (
    /(^|\/)(tokens?|theme|variables|design-tokens)\.(css|scss|[jt]sx?|json)$/.test(p) ||
    /(^|\/)ui\/theme\/(color|theme|type|shape|spacing)\.kt$/.test(p) ||
    /(^|\/)res\/values(-[a-z0-9-]+)?\/(colors|themes|styles|type|dimens)\.xml$/.test(p) ||
    /tailwind\.config\.[cm]?[jt]s$/.test(p)
  );
}

/** Replaces comment text with spaces, keeping newlines so line numbers stay valid. */
export function stripComments(content: string, lang: Lang): string {
  const out = content.split('');
  const blank = (from: number, to: number) => {
    for (let i = from; i < to && i < out.length; i++) if (out[i] !== '\n') out[i] = ' ';
  };
  if (lang === 'html' || lang === 'xml') {
    const re = /<!--[\s\S]*?-->/g;
    for (let m = re.exec(content); m; m = re.exec(content)) blank(m.index, m.index + m[0].length);
    return out.join('');
  }
  if (lang === 'other') return content;
  const lineComments = lang !== 'css';
  let i = 0;
  let quote: string | null = null;
  while (i < content.length) {
    const ch = content[i]!;
    const next = content[i + 1];
    if (quote) {
      if (ch === '\\') i += 2;
      else {
        if (ch === quote || (ch === '\n' && quote !== '`')) quote = null;
        i++;
      }
      continue;
    }
    if (ch === '"' || ch === "'" || (ch === '`' && lang !== 'css')) {
      quote = ch;
      i++;
      continue;
    }
    if (ch === '/' && next === '*') {
      const end = content.indexOf('*/', i + 2);
      const stop = end === -1 ? content.length : end + 2;
      blank(i, stop);
      i = stop;
      continue;
    }
    if (lineComments && ch === '/' && next === '/' && content[i - 1] !== ':') {
      const end = content.indexOf('\n', i);
      const stop = end === -1 ? content.length : end;
      blank(i, stop);
      i = stop;
      continue;
    }
    i++;
  }
  return out.join('');
}

/** 1-based line number of a character offset. */
export function lineAt(content: string, offset: number): number {
  let line = 1;
  for (let i = 0; i < offset && i < content.length; i++) if (content[i] === '\n') line++;
  return line;
}

/** Iterates regex matches with their 1-based line numbers. */
export function* matches(
  content: string,
  re: RegExp,
): Generator<{ m: RegExpExecArray; line: number }> {
  const flags = re.flags.includes('g') ? re.flags : `${re.flags}g`;
  const g = new RegExp(re.source, flags);
  let lastIndex = 0;
  let line = 1;
  for (let m = g.exec(content); m; m = g.exec(content)) {
    for (let i = lastIndex; i < m.index; i++) if (content[i] === '\n') line++;
    lastIndex = m.index;
    yield { m, line };
    if (m[0].length === 0) g.lastIndex++;
  }
}

export interface Tag {
  name: string;
  attrs: string;
  line: number;
  index: number;
  selfClosing: boolean;
}

/** Lightweight scan of opening tags in HTML, JSX or XML (good enough for lint heuristics). */
export function openingTags(content: string): Tag[] {
  const tags: Tag[] = [];
  for (const { m, line } of matches(
    content,
    /<([A-Za-z][\w.:-]*)((?:\s+(?:[^\s"'>/=]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|\{(?:[^{}]|\{[^{}]*\})*\}|[^\s"'>]+))?))*)\s*(\/?)>/,
  )) {
    tags.push({ name: m[1]!, attrs: m[2] ?? '', line, index: m.index, selfClosing: m[3] === '/' });
  }
  return tags;
}

/** Reads an attribute value from a tag's attribute string (quoted or {expression}). */
export function attr(attrs: string, name: string): string | undefined {
  const re = new RegExp(
    `(?:^|\\s)${name.replace(/[.:]/g, '\\$&')}\\s*=\\s*("([^"]*)"|'([^']*)'|\\{([\\s\\S]*?)\\}(?=\\s|$))`,
  );
  const m = re.exec(attrs);
  if (!m) return undefined;
  return m[2] ?? m[3] ?? m[4] ?? '';
}

export function hasAttr(attrs: string, name: string): boolean {
  return new RegExp(`(?:^|\\s)${name.replace(/[.:]/g, '\\$&')}(?:\\s*=|\\s|$)`).test(attrs);
}
